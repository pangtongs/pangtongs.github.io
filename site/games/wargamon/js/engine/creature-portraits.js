const creatureArtMissing = file =>
  !!file && typeof CREATURE_ART_MISSING !== 'undefined' && CREATURE_ART_MISSING.includes(file);
// True while a species still shows the placeholder instead of its portrait.
const creaturePortraitPending = id => creatureArtMissing(CREATURE_PORTRAITS[id]);
// A follower sheet that exists; null while it is missing (the follower then uses the portrait).
const creatureFollowerFile = id =>
  CREATURE_FOLLOWER_FILES[id] && !creatureArtMissing(CREATURE_FOLLOWER_FILES[id])
    ? CREATURE_FOLLOWER_FILES[id]
    : null;
// One placeholder image per species (512 × 512 SVG): a magenta and black checkerboard, a big
// "?" and the dex number from the expected file name. No download, so it never fails offline.
const creaturePlaceholders = new Map();
function creaturePlaceholder(id) {
  if (!creaturePlaceholders.has(id)) {
    const number = (CREATURE_PORTRAITS[id] || '').match(/\/(\d{3})-/)?.[1] || '';
    creaturePlaceholders.set(
      id,
      'data:image/svg+xml,' +
        encodeURIComponent(
          `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" data-species="${id}"><defs><pattern id="c" width="64" height="64" patternUnits="userSpaceOnUse"><rect width="64" height="64" fill="#1a1a1a"/><rect width="32" height="32" fill="#ff2bd6"/><rect x="32" y="32" width="32" height="32" fill="#ff2bd6"/></pattern></defs><rect x="16" y="16" width="480" height="480" rx="48" fill="url(#c)" stroke="#fff" stroke-width="16"/><text x="256" y="350" text-anchor="middle" font-family="Arial,sans-serif" font-weight="900" font-size="300" fill="#fff" stroke="#000" stroke-width="12" paint-order="stroke">?</text><text x="256" y="452" text-anchor="middle" font-family="Arial,sans-serif" font-weight="900" font-size="56" fill="#fff" stroke="#000" stroke-width="8" paint-order="stroke">#${number}</text></svg>`,
        ),
    );
  }
  return creaturePlaceholders.get(id);
}
function creaturePortraitPath(id) {
  const file = CREATURE_PORTRAITS[id] || null;
  return file && creatureArtMissing(file) ? creaturePlaceholder(id) : file;
}
