/* One portrait path per stable species ID, and the loud placeholder for art that is not
   delivered yet.

   CREATURE_ART_MISSING (js/data/creature-art-missing.js) is generated by
   scripts/build-creature-art.cjs from the files that exist in web/img: every portrait in
   CREATURE_PORTRAITS and every sheet in CREATURE_FOLLOWER_FILES that is not there yet.
   Such a species shows a checkered magenta "?" card (the same loud look as a resident
   without a sprite) in menus, the Wargadex, battles and, as its follower, on the map.
   Dropping the real file into web/img and running npm run build:generated switches the
   placeholder off: nothing else needs editing. */
