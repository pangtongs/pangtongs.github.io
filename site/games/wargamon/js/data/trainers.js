function trainerName(id, short = true) {
  const trainer = TRAINERS[id];
  if (!trainer || !trainer.name) throw new Error(`Unknown trainer ID ${id}`);
  return short ? trainer.name.split(' ')[0] : trainer.name;
}
function trainerText(key, fallback, refs) {
  const catalogs = globalThis.WARGAMON_MESSAGES;
  const locale =
    typeof localStorage === 'undefined'
      ? 'id'
      : localStorage.getItem('wargamon-language') === 'en'
        ? 'en'
        : 'id';
  const template = catalogs?.[locale]?.[key] ?? catalogs?.id?.[key] ?? fallback;
  const params = Object.fromEntries(
    Object.entries(refs).map(([name, ref]) => [
      name,
      Array.isArray(ref) ? trainerName(ref[0], ref[1]) : trainerName(ref),
    ]),
  );
  return template.replace(/\{(trainer\d+)\}/g, (token, name) => {
    if (!(name in params)) throw new Error(`Missing trainer reference ${name} in ${key}`);
    return params[name];
  });
}
