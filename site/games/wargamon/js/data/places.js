/* Outdoor places by region and indoor rooms by key, with their activity points. */
const marker = (key, name, x, y, extra = {}) => ({
  key,
  name,
  x,
  y,
  mark:
    key === 'wild'
      ? '♧'
      : key === 'next'
        ? '↑'
        : key === 'back'
          ? '↓'
          : key === 'door'
            ? '↵'
            : key === 'heal'
              ? '✚'
              : '!',
  color: key === 'wild' ? '#c6ff8b' : '#f3dc9a',
  ...extra,
});
// A point that stands for a character reads its portrait from the character's record,
// so the map and the dialog always agree.
function bindCharacter(point, character) {
  Object.defineProperty(point, 'portrait', {
    enumerable: true,
    configurable: false,
    get: () => character.portrait,
    set: value => {
      character.portrait = value;
    },
  });
  return point;
}
function characterMarker(key, character, x, y, extra = {}) {
  return bindCharacter(marker(key, character.name || character.speaker, x, y, extra), character);
}
